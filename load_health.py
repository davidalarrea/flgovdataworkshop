import base64, gzip, io, pandas as pd

try:
    spark.sql(f'CREATE CATALOG IF NOT EXISTS {CATALOG}')
except Exception as e:
    print(f'Could not create catalog {CATALOG!r} ({e}).')
    print('Set CATALOG above to one you can already write to, then Run All again.')
    raise

spark.sql(f'CREATE SCHEMA IF NOT EXISTS {CATALOG}.{SCHEMA}')

for name, (cols, b64) in TABLES.items():
    csv_text = gzip.decompress(base64.b64decode(b64)).decode('utf-8')
    # read every column as a string first; empty cells stay '' (not NaN)
    pdf = pd.read_csv(io.StringIO(csv_text), dtype=str, keep_default_na=False)
    sdf = spark.createDataFrame(pdf)
    view = f'_stg_{name}'
    sdf.createOrReplaceTempView(view)
    select_expr = ',\n           '.join(
        (f'NULLIF(`{c}`, \'\') AS {c}' if t == 'STRING'
         else f'CAST(NULLIF(`{c}`, \'\') AS {t}) AS {c}')
        for c, t in cols)
    fq = f'{CATALOG}.{SCHEMA}.{name}'
    spark.sql(f'DROP TABLE IF EXISTS {fq}')
    spark.sql(f'CREATE TABLE {fq} AS SELECT {select_expr} FROM {view}')
    n = spark.table(fq).count()
    print(f'  created {fq}  ({n:,} rows)')

print('\nDone. Point a Genie space at the three tables in '
      f'{CATALOG}.{SCHEMA} to begin.')

